package DSA_Pattern;

public class Pattern_0_STL_1 {
    public static void main(String[] args) {
        System.out.println(num(345));
    }
    public static String num(int n) {
        String s1 = "Hello";
        String s2 = " World";
        String s3 = s1 + s2;
        return n / 10 + " " + s3;
    }
}
